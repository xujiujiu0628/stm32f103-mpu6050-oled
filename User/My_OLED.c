/**
  * @brief  显示图像
  * @param  X: 起始列位置
  * @param  Y: 起始行位置
  * @param  Width: 图像宽度（像素）
  * @param  Height: 图像高度
  * @param  Image: 图像数据指针
  * @retval 无
  */
void My_OLED_ShowImage(uint8_t X, uint8_t Y, uint8_t Width, uint8_t Height, const uint8_t *Image)
{
	My_OLED_ClearArea(X,Y,Width,Height);  // 先清除显示区域
	for(uint8_t j=0;j<(Height-1)/8+1;j++)  // 计算需要的页数
	{
		for(uint8_t i=0;i<Width;i++)  // 遍历图像宽度
		{
			// 将图像数据写入显示缓冲区，处理跨页情况
			// 2026-09-06 越界修复：原版无条件写 Y/8+j+1（跨页第二行），
			// 字符显示在底部（y≥48 用 8x16 / y=56 用 6x8）时页索引 ≥8，
			// 越界写覆盖 .bss 相邻变量（曾污染 key.c/mpu6050.c 状态导致真机误触发）。
			if((Y/8+j)<8 && (X+i)<128)
			{
				My_OLED_DisplayBuf[Y/8+j][X+i]|=Image[j*Width+i]<<(Y % 8);
			}
			if((Y/8+j+1)<8 && (X+i)<128)
			{
				My_OLED_DisplayBuf[Y/8+j+1][X+i]|=Image[j*Width+i]>>(8- Y % 8);
			}
		}
	}
}
  
/**
  * @brief  显示中文字符串
  * @param  X: 起始列位置
  * @param  Y: 起始行位置
  * @param  Chinese: 要显示的中文字符串
  * @retval 无
  */
void My_OLED_ShowChinese(uint8_t X,uint8_t Y,char *Chinese)
{
	char SigleChinese[3]={0};  // 存储单个汉字（2字节+结束符）
	uint8_t pChinese=0;        // 汉字字节计数器
	uint8_t pIndex;            // 字库索引
	
	for(uint8_t i=0;Chinese[i]!='\0';i++)  // 遍历中文字符串
	{
		SigleChinese[pChinese]=Chinese [i];  // 存储汉字字节
		pChinese++;
		
		if(pChinese>=2)  // 收集完一个汉字（2字节）
		{
			pChinese=0;  // 重置计数器

			// 在字库中查找对应的汉字
			for(pIndex=0;strcmp(My_OLED_CF16x16[pIndex].Index,"")!=0;pIndex++)
			{
				if(strcmp(My_OLED_CF16x16[pIndex].Index,SigleChinese)==0)
				{
					break;  // 找到汉字，退出循环
				}
			}
			// 显示找到的汉字（16x16像素，占2页高度）
			My_OLED_ShowImage(X+((i+1)/2-1)*16,Y,16,16,My_OLED_CF16x16[pIndex].Data);
		}
	}
} 

